-- Permissions des deux référentiels.
INSERT INTO permission(code, name, module, description, active)
SELECT v.code, v.name, 'PERSONNEL', v.description, TRUE
FROM (VALUES
    ('MATIERE_CONSULTER', 'Consulter les matières', 'Consulter le référentiel des matières'),
    ('MATIERE_GERER', 'Gérer les matières', 'Créer, modifier, activer ou désactiver une matière'),
    ('POSTE_CONSULTER', 'Consulter les postes', 'Consulter le référentiel des postes et fonctions'),
    ('POSTE_GERER', 'Gérer les postes', 'Créer, modifier, activer ou désactiver un poste ou une fonction')
) AS v(code, name, description)
WHERE NOT EXISTS (SELECT 1 FROM permission p WHERE p.code = v.code);

INSERT INTO role_permission(role_id, permission_id)
SELECT r.id, p.id
FROM role r
CROSS JOIN permission p
WHERE r.code = 'ADMIN'
  AND p.code IN ('MATIERE_CONSULTER','MATIERE_GERER','POSTE_CONSULTER','POSTE_GERER')
  AND NOT EXISTS (
      SELECT 1 FROM role_permission rp
      WHERE rp.role_id = r.id AND rp.permission_id = p.id
  );

INSERT INTO role_permission(role_id, permission_id)
