-- V16 - Référentiels RH : matières administrables et postes/fonctions.
-- IMPORTANT : ne modifie aucune migration V1 à V15.

CREATE TABLE IF NOT EXISTS job_position (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(60) NOT NULL,
    name VARCHAR(150) NOT NULL,
    category VARCHAR(60),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    display_order INTEGER,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_job_position_code_ci
    ON job_position (LOWER(code));
CREATE UNIQUE INDEX IF NOT EXISTS uq_job_position_name_ci
    ON job_position (LOWER(name));
CREATE INDEX IF NOT EXISTS idx_job_position_active_order
    ON job_position (active, display_order, name);

