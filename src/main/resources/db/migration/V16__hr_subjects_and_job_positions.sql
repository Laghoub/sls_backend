-- Reprise des éventuels intitulés déjà présents avant V16 afin de ne perdre aucune donnée.
INSERT INTO job_position(code, name, category, active, display_order)
SELECT
    'LEGACY_' || UPPER(SUBSTRING(MD5(TRIM(e.position_title)) FROM 1 FOR 12)),
    TRIM(e.position_title),
    'AUTRE',
    TRUE,
    900
FROM employee e
WHERE e.position_title IS NOT NULL
  AND TRIM(e.position_title) <> ''
  AND NOT EXISTS (
      SELECT 1 FROM job_position jp
      WHERE LOWER(TRIM(jp.name)) = LOWER(TRIM(e.position_title))
  )
GROUP BY TRIM(e.position_title)
ON CONFLICT DO NOTHING;

ALTER TABLE employee
    ADD COLUMN IF NOT EXISTS position_id BIGINT;

UPDATE employee e
SET position_id = jp.id
FROM job_position jp
WHERE e.position_id IS NULL
  AND LOWER(TRIM(jp.name)) = LOWER(TRIM(e.position_title));

-- Sécurité pour d'éventuelles anciennes lignes avec un intitulé vide ou atypique.
UPDATE employee e
SET position_id = jp.id,
    position_title = CASE WHEN TRIM(COALESCE(e.position_title, '')) = '' THEN jp.name ELSE e.position_title END
FROM job_position jp
WHERE e.position_id IS NULL
  AND jp.code = 'AUTRE';

ALTER TABLE employee
    DROP CONSTRAINT IF EXISTS fk_employee_job_position;
ALTER TABLE employee
    ADD CONSTRAINT fk_employee_job_position
    FOREIGN KEY (position_id) REFERENCES job_position(id) ON DELETE RESTRICT;

-- Toute ligne employee historique possédait déjà position_title NOT NULL : le backfill ci-dessus
