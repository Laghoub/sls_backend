-- =========================================================
-- ADMIN : tous les droits réduction
-- =========================================================

INSERT INTO role_permission (
    role_id,
    permission_id
)
SELECT
    r.id,
    p.id
FROM role r
         CROSS JOIN permission p
WHERE r.code = 'ADMIN'
  AND p.code IN (
                 'REDUCTION_CONSULTER',
                 'REDUCTION_CREER',
                 'REDUCTION_VALIDER',
                 'REDUCTION_REFUSER',
                 'REDUCTION_PARAMETRER'
    )
    ON CONFLICT DO NOTHING;


