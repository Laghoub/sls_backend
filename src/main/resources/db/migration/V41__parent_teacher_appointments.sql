CREATE TABLE parent_teacher_appointment (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 guardian_id BIGINT NOT NULL REFERENCES guardian(id),
 student_id BIGINT NOT NULL REFERENCES student(id),
 teacher_id BIGINT NOT NULL REFERENCES teacher(id),
 subject_id BIGINT NOT NULL REFERENCES subject(id),
 reason VARCHAR(1000) NOT NULL,
 preferred_times TEXT,
 status VARCHAR(30) NOT NULL DEFAULT 'PENDING' CHECK(status IN ('PENDING','CONFIRMED','REJECTED','CANCELLED')),
 starts_at TIMESTAMPTZ,
 ends_at TIMESTAMPTZ,
 meeting_place VARCHAR(250),
 decision_note TEXT,
 decided_by BIGINT REFERENCES user_account(id),
 decided_at TIMESTAMPTZ,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 CONSTRAINT chk_appointment_dates CHECK (starts_at IS NULL OR (ends_at IS NOT NULL AND ends_at > starts_at))
);
CREATE INDEX idx_appointment_guardian ON parent_teacher_appointment(guardian_id,created_at DESC);
CREATE INDEX idx_appointment_teacher ON parent_teacher_appointment(teacher_id,starts_at);
CREATE INDEX idx_appointment_status ON parent_teacher_appointment(status,created_at DESC);
CREATE TABLE parent_teacher_appointment_mail (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 appointment_id BIGINT NOT NULL REFERENCES parent_teacher_appointment(id),
 recipient_email VARCHAR(250) NOT NULL,
 subject VARCHAR(250) NOT NULL,
 body TEXT NOT NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK(status IN ('PENDING','SENDING','SENT','FAILED')),
 attempts INTEGER NOT NULL DEFAULT 0,
 next_attempt_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 last_error TEXT,
 sent_at TIMESTAMPTZ,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_appointment_mail_retry ON parent_teacher_appointment_mail(status,next_attempt_at);
