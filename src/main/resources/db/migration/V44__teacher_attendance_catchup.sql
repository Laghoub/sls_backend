-- V45 application : régularisation historique sans modification du pointage quotidien.
CREATE TABLE teacher_attendance_catchup (
 teacher_attendance_id BIGINT PRIMARY KEY REFERENCES teacher_attendance(id) ON DELETE RESTRICT,
 created_by BIGINT NOT NULL REFERENCES user_account(id),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE teacher_attendance_catchup_template (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(120) NOT NULL,
 from_date DATE NOT NULL,
 to_date DATE NOT NULL,
 created_by BIGINT NOT NULL REFERENCES user_account(id),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 CONSTRAINT chk_catchup_template_dates CHECK (from_date<=to_date)
);
CREATE TABLE teacher_attendance_catchup_pattern (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 template_id BIGINT NOT NULL REFERENCES teacher_attendance_catchup_template(id) ON DELETE CASCADE,
 teacher_id BIGINT NOT NULL REFERENCES teacher(id),
 class_group_id BIGINT NOT NULL REFERENCES class_group(id),
 subject_id BIGINT NOT NULL REFERENCES subject(id),
 time_slot_id BIGINT NOT NULL REFERENCES time_slot(id),
 day_of_week SMALLINT NOT NULL CHECK(day_of_week BETWEEN 1 AND 7),
 CONSTRAINT uq_catchup_pattern UNIQUE(template_id,teacher_id,day_of_week,time_slot_id,class_group_id)
);
CREATE TABLE teacher_attendance_catchup_excluded_date (
 day DATE PRIMARY KEY,
 reason VARCHAR(200)
);
CREATE INDEX idx_catchup_pattern_template ON teacher_attendance_catchup_pattern(template_id);
