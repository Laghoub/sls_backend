-- Historique des menus de cantine par semaine (dimanche a jeudi).
CREATE TABLE canteen_weekly_menu (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 week_start DATE NOT NULL UNIQUE,
 status VARCHAR(12) NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT','PUBLISHED')),
 published_at TIMESTAMPTZ,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 CONSTRAINT chk_canteen_week_start CHECK (EXTRACT(ISODOW FROM week_start)=7)
);
CREATE TABLE canteen_menu_day (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 menu_id BIGINT NOT NULL REFERENCES canteen_weekly_menu(id) ON DELETE CASCADE,
 meal_date DATE NOT NULL,
 starter TEXT,
 main_course TEXT NOT NULL,
 side_dish TEXT,
 dessert TEXT,
 notes TEXT,
 UNIQUE(menu_id,meal_date)
);
CREATE INDEX idx_canteen_menu_day_menu ON canteen_menu_day(menu_id);
