-- V36: independent staff attendance and payroll, linked to existing employee records.
CREATE TABLE staff_pay_contract (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 employee_id BIGINT NOT NULL REFERENCES employee(id),
 pay_type VARCHAR(12) NOT NULL CHECK(pay_type IN ('MONTHLY','DAILY','HOURLY')),
 base_rate NUMERIC(14,2) NOT NULL CHECK(base_rate >= 0),
 effective_from DATE NOT NULL,
 effective_to DATE,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 CHECK(effective_to IS NULL OR effective_to >= effective_from)
);
CREATE INDEX idx_staff_contract_employee ON staff_pay_contract(employee_id,effective_from);
CREATE TABLE staff_attendance (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 employee_id BIGINT NOT NULL REFERENCES employee(id),
 work_date DATE NOT NULL,
 status VARCHAR(24) NOT NULL CHECK(status IN ('PRESENT','LATE','ABSENT_EXCUSED','ABSENT_UNEXCUSED','LEAVE','SICK','REST')),
 check_in TIME, check_out TIME, worked_minutes INTEGER CHECK(worked_minutes >= 0),
 paid BOOLEAN NOT NULL DEFAULT TRUE,
 note TEXT,
 updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE(employee_id,work_date)
);
CREATE INDEX idx_staff_attendance_date ON staff_attendance(work_date);
CREATE TABLE staff_pay_run (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 employee_id BIGINT NOT NULL REFERENCES employee(id),
 pay_month DATE NOT NULL CHECK(EXTRACT(DAY FROM pay_month)=1),
 contract_id BIGINT NOT NULL REFERENCES staff_pay_contract(id),
 base_amount NUMERIC(14,2) NOT NULL CHECK(base_amount>=0),
 bonus_amount NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK(bonus_amount>=0),
 deduction_amount NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK(deduction_amount>=0),
 net_amount NUMERIC(14,2) NOT NULL CHECK(net_amount>=0),
 status VARCHAR(16) NOT NULL DEFAULT 'DRAFT' CHECK(status IN ('DRAFT','APPROVED','CANCELLED')),
 note TEXT,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 approved_at TIMESTAMPTZ,
 UNIQUE(employee_id,pay_month)
);
CREATE TABLE staff_pay_payment (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 pay_run_id BIGINT NOT NULL REFERENCES staff_pay_run(id),
 amount NUMERIC(14,2) NOT NULL CHECK(amount>0),
 paid_on DATE NOT NULL,
 payment_method VARCHAR(40) NOT NULL,
 reference VARCHAR(150),
 note TEXT,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_staff_payment_run ON staff_pay_payment(pay_run_id);
