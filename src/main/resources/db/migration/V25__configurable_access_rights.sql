-- V25 - Gestion configurable des profils et droits d'accès

CREATE TABLE IF NOT EXISTS user_permission_override (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_account_id BIGINT NOT NULL REFERENCES user_account(id) ON DELETE CASCADE,
    permission_id BIGINT NOT NULL REFERENCES permission(id) ON DELETE CASCADE,
    effect VARCHAR(10) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_user_permission_override UNIQUE (user_account_id, permission_id),
    CONSTRAINT ck_user_permission_override_effect CHECK (effect IN ('GRANT','DENY'))
);

CREATE INDEX IF NOT EXISTS idx_user_permission_override_user ON user_permission_override(user_account_id);

INSERT INTO permission(code,name,module,description,active) VALUES
 ('ROLE_GERER','Gérer les profils','SECURITY','Créer, modifier et désactiver les profils.',TRUE),
 ('PERMISSION_GERER','Gérer les droits des profils','SECURITY','Configurer les permissions affectées aux profils.',TRUE),
 ('UTILISATEUR_DROITS_GERER','Gérer les droits individuels','SECURITY','Configurer rôles, exceptions et périmètres d’un utilisateur.',TRUE)
ON CONFLICT (code) DO NOTHING;

-- L'administrateur reçoit toujours toutes les permissions connues.
INSERT INTO role_permission(role_id,permission_id)
SELECT r.id,p.id FROM role r CROSS JOIN permission p WHERE r.code='ADMIN'
ON CONFLICT DO NOTHING;
