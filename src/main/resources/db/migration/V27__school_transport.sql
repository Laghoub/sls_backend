-- V27 - Module Transport scolaire V1
-- Le schéma initial V1 contient déjà transport_route et transport_stop.
-- Cette migration étend ces tables au lieu de les recréer.

CREATE TABLE transport_vehicle (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, code VARCHAR(30) NOT NULL UNIQUE, registration_number VARCHAR(50) NOT NULL UNIQUE,
 brand VARCHAR(80), model VARCHAR(80), capacity INTEGER NOT NULL CHECK(capacity > 0), insurance_expiry DATE, technical_inspection_expiry DATE,
 status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE', notes TEXT, created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE transport_driver (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, last_name VARCHAR(100) NOT NULL, first_name VARCHAR(100) NOT NULL, phone VARCHAR(30),
 license_number VARCHAR(80) NOT NULL UNIQUE, license_expiry DATE, status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE', notes TEXT,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP);

ALTER TABLE transport_route ADD COLUMN IF NOT EXISTS vehicle_id BIGINT REFERENCES transport_vehicle(id);
ALTER TABLE transport_route ADD COLUMN IF NOT EXISTS driver_id BIGINT REFERENCES transport_driver(id);
ALTER TABLE transport_route ADD COLUMN IF NOT EXISTS morning_departure TIME;
ALTER TABLE transport_route ADD COLUMN IF NOT EXISTS return_departure TIME;
ALTER TABLE transport_route ADD COLUMN IF NOT EXISTS active BOOLEAN NOT NULL DEFAULT TRUE;
ALTER TABLE transport_route ADD COLUMN IF NOT EXISTS notes TEXT;
ALTER TABLE transport_route ALTER COLUMN route_type SET DEFAULT 'SCHOOL';
ALTER TABLE transport_route ALTER COLUMN status SET DEFAULT 'ACTIVE';

-- Les arrêts existent déjà dans V1. On ajoute uniquement les informations de circuit
-- nécessaires à l'API V1 actuelle. Les colonnes restent compatibles avec route_stop.
ALTER TABLE transport_stop ADD COLUMN IF NOT EXISTS route_id BIGINT REFERENCES transport_route(id) ON DELETE CASCADE;
ALTER TABLE transport_stop ADD COLUMN IF NOT EXISTS stop_order INTEGER;
ALTER TABLE transport_stop ADD COLUMN IF NOT EXISTS morning_time TIME;
ALTER TABLE transport_stop ADD COLUMN IF NOT EXISTS return_time TIME;
ALTER TABLE transport_stop ALTER COLUMN code DROP NOT NULL;
ALTER TABLE transport_stop ALTER COLUMN created_at SET DEFAULT CURRENT_TIMESTAMP;
ALTER TABLE transport_stop ALTER COLUMN updated_at SET DEFAULT CURRENT_TIMESTAMP;
CREATE UNIQUE INDEX IF NOT EXISTS uq_transport_stop_route_order_v27 ON transport_stop(route_id,stop_order) WHERE route_id IS NOT NULL AND stop_order IS NOT NULL;

CREATE TABLE student_transport_assignment (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, student_enrollment_id BIGINT NOT NULL REFERENCES student_enrollment(id), route_id BIGINT NOT NULL REFERENCES transport_route(id),
 stop_id BIGINT NOT NULL REFERENCES transport_stop(id), service_type VARCHAR(20) NOT NULL CHECK(service_type IN ('ROUND_TRIP','OUTBOUND_ONLY','RETURN_ONLY')),
 monthly_fee NUMERIC(14,2) NOT NULL CHECK(monthly_fee >= 0), start_date DATE NOT NULL, end_date DATE, status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP);
CREATE INDEX idx_transport_assignment_enrollment ON student_transport_assignment(student_enrollment_id,status);
CREATE INDEX idx_transport_assignment_route ON student_transport_assignment(route_id,status);
