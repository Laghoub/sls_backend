-- Planning administratif des devoirs et examens (distinct des notes).
CREATE TABLE assessment_schedule (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 school_year_id BIGINT NOT NULL REFERENCES school_year(id),
 class_group_id BIGINT NOT NULL REFERENCES class_group(id),
 assessment_type VARCHAR(12) NOT NULL CHECK(assessment_type IN ('DEVOIR','EXAMEN')),
 term SMALLINT NOT NULL CHECK(term BETWEEN 1 AND 3),
 title VARCHAR(200) NOT NULL,
 status VARCHAR(12) NOT NULL DEFAULT 'DRAFT' CHECK(status IN ('DRAFT','PUBLISHED','ARCHIVED')),
 published_at TIMESTAMPTZ,
 created_by BIGINT NOT NULL REFERENCES user_account(id),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 CONSTRAINT uq_assessment_schedule UNIQUE(school_year_id,class_group_id,assessment_type,term),
 CONSTRAINT chk_assessment_publication CHECK(status='DRAFT' OR published_at IS NOT NULL)
);
CREATE TABLE assessment_schedule_entry (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 schedule_id BIGINT NOT NULL REFERENCES assessment_schedule(id) ON DELETE CASCADE,
 subject_id BIGINT NOT NULL REFERENCES subject(id),
 assessment_date DATE NOT NULL,
 start_time TIME NOT NULL, end_time TIME NOT NULL,
 room VARCHAR(100), instructions TEXT,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 CONSTRAINT chk_assessment_hours CHECK(start_time<end_time),
 CONSTRAINT uq_assessment_subject_day UNIQUE(schedule_id,subject_id,assessment_date,start_time)
);
CREATE INDEX idx_assessment_entries_date ON assessment_schedule_entry(assessment_date);
CREATE INDEX idx_assessment_schedule_class ON assessment_schedule(class_group_id,status);
